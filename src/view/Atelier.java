    private void refreshTable() {

    DefaultTableModel tableModel =
            (DefaultTableModel) jTable1.getModel();

    tableModel.setRowCount(0);

    for (Exhibitor exhibitor : controller.getAllExhibitors()) {

        tableModel.addRow(new Object[] {
            exhibitor.getExhibitorId(),
            exhibitor.getName(),
            exhibitor.getMedium(),
            exhibitor.getArtworkCount(),
            exhibitor.getStatus()
        });
    }
}
    
private ExhibitorController controller =
        new ExhibitorController();
private void searchExhibitorById(String id) {

    Exhibitor exhibitor = controller.searchExhibitor(id);

    if (exhibitor != null) {

        DefaultTableModel model =
                (DefaultTableModel) jTable1.getModel();

        model.setRowCount(0);

        model.addRow(new Object[]{
            exhibitor.getExhibitorId(),
            exhibitor.getName(),
            exhibitor.getMedium(),
            exhibitor.getArtworkCount(),
            exhibitor.getStatus()
        });

    } else {

        JOptionPane.showMessageDialog(this,
                "Exhibitor ID not found.");
    }
}

