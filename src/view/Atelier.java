    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String name = jTextField1.getText().trim();
String medium = jTextField2.getText().trim();

try {

    int artworkCount =
            Integer.parseInt(jTextField3.getText().trim());

    String status = "";

    if (jCheckBox1.isSelected()) {
        status = "ACTIVE";
    } else if (jCheckBox2.isSelected()) {
        status = "SCHEDULED";
    } else if (jCheckBox3.isSelected()) {
        status = "COMPLETED";
    }

    if (name.isEmpty() || medium.isEmpty() || status.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please complete all exhibitor information.");
        return;
    }

    if (artworkCount < 0) {
        JOptionPane.showMessageDialog(this,
                "Artwork count cannot be negative.");
        return;
    }

    controller.addExhibitor(
            name, medium, artworkCount, status
    );

    refreshTable();

    jTextField1.setText("");
    jTextField2.setText("");
    jTextField3.setText("");

    jCheckBox1.setSelected(false);
    jCheckBox2.setSelected(false);
    jCheckBox3.setSelected(false);

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this,
            "Enter a valid artwork count.");
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int selectedRow = jTable1.getSelectedRow();

if (selectedRow == -1) {

    JOptionPane.showMessageDialog(this,
            "Please select an exhibitor to remove.");

    return;
}

String id = jTable1.getValueAt(selectedRow, 0).toString();

if (controller.removeExhibitor(id)) {

    refreshTable();

    JOptionPane.showMessageDialog(this,
            "Exhibitor removed successfully.");
}
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int selectedRow = jTable1.getSelectedRow();

if (selectedRow == -1) {

    JOptionPane.showMessageDialog(this,
            "Please select an exhibitor to update.");

    return;
}

String id = jTable1.getValueAt(selectedRow, 0).toString();

String name = jTextField1.getText().trim();
String medium = jTextField2.getText().trim();

try {

    int artworkCount =
            Integer.parseInt(jTextField3.getText().trim());

    String status = "";

    if (jCheckBox1.isSelected()) {
        status = "ACTIVE";
    } else if (jCheckBox2.isSelected()) {
        status = "SCHEDULED";
    } else if (jCheckBox3.isSelected()) {
        status = "COMPLETED";
    }

    if (name.isEmpty() || medium.isEmpty() || status.isEmpty()
            || artworkCount < 0) {

        JOptionPane.showMessageDialog(this,
                "Please enter valid exhibitor information.");

        return;
    }

    if (controller.updateExhibitor(
            id, name, medium, artworkCount, status)) {

        refreshTable();

        JOptionPane.showMessageDialog(this,
                "Exhibitor updated successfully.");
    }

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this,
            "Enter a valid artwork count.");
}
    }//GEN-LAST:event_jButton3ActionPerformed

